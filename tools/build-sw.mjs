#!/usr/bin/env node
// Writes sw.js with the full precache list and a version derived from the
// content of every cached file, so any change ships a fresh offline cache.
// Run after changing app files: node tools/build-sw.mjs  (npm test checks it is current)
import { readFileSync, writeFileSync, readdirSync, statSync } from 'node:fs';
import { createHash } from 'node:crypto';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');

export function listAssets() {
  const out = ['index.html', 'manifest.webmanifest'];
  const walk = (dir, exts) => {
    for (const name of readdirSync(join(root, dir)).sort()) {
      const rel = join(dir, name);
      if (statSync(join(root, rel)).isDirectory()) walk(rel, exts);
      else if (exts.some((e) => name.endsWith(e))) out.push(rel.split('\\').join('/'));
    }
  };
  walk('css', ['.css']);
  walk('js', ['.js']);
  walk('data', ['.json']);
  walk('icons', ['.png', '.svg']);
  return out;
}

export function assetVersion(assets) {
  const h = createHash('sha256');
  for (const a of assets) { h.update(a); h.update(readFileSync(join(root, a))); }
  return h.digest('hex').slice(0, 12);
}

export function renderServiceWorker() {
  const assets = listAssets();
  const version = assetVersion(assets);
  return `// GENERATED by tools/build-sw.mjs — do not edit by hand.
// Offline-first service worker: everything the app needs is precached on
// install and served from the cache; the network is never required.
const VERSION = '${version}';
const CACHE = 'star-sky-' + VERSION;
const ASSETS = ${JSON.stringify(['./', ...assets.map((a) => './' + a)], null, 2)};

self.addEventListener('install', (event) => {
  event.waitUntil(caches.open(CACHE).then((cache) => cache.addAll(ASSETS)).then(() => self.skipWaiting()));
});

self.addEventListener('activate', (event) => {
  event.waitUntil(
    caches.keys()
      .then((keys) => Promise.all(keys.filter((k) => k.startsWith('star-sky-') && k !== CACHE).map((k) => caches.delete(k))))
      .then(() => self.clients.claim()),
  );
});

self.addEventListener('fetch', (event) => {
  const req = event.request;
  if (req.method !== 'GET') return;
  const url = new URL(req.url);
  if (url.origin !== self.location.origin) return;
  event.respondWith(
    caches.match(req, { ignoreSearch: true }).then((hit) => {
      if (hit) return hit;
      if (req.mode === 'navigate') return caches.match('./index.html').then((page) => page || fetch(req));
      return fetch(req);
    }),
  );
});
`;
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  const text = renderServiceWorker();
  writeFileSync(join(root, 'sw.js'), text);
  console.log(`wrote sw.js (${listAssets().length} assets, version ${text.match(/VERSION = '(\w+)'/)[1]})`);
}

